#!/usr/bin/env python3
"""Add Node.js 22 and npm to an Alpine fakefs rootfs tree.

OpenMinis' sandbox can run Node scripts and package installs; Alpine's
minirootfs only carries busybox and apk, and the guest cannot download
packages at runtime. The pinned package set below is fetched at build time
and unpacked straight into the rootfs directory, the same way
ish-rootfs-python.py adds Python.

Node's Alpine build also needs a CA bundle, which is normally generated by
the ca-certificates post-install script. apk control scripts are skipped
here, so the bundle is assembled from the shipped PEM files instead.

Usage:
    python3 -I scripts/ish-rootfs-node.py \
        --data build/ish-ohos/rootfs/data \
        --cache build/ish-ohos/cache/node-apks

Run this before create_fakefs.py. It is idempotent.
"""

import argparse
import glob
import hashlib
import os
import subprocess
import tarfile

MAIN = "https://dl-cdn.alpinelinux.org/alpine/v3.21/main/aarch64"
COMMUNITY = "https://dl-cdn.alpinelinux.org/alpine/v3.21/community/aarch64"

# nodejs 22.23.4-r0 (main), npm 10.9.1-r0 (community) and the part of their
# dependency closure that the Python set does not already provide, pinned by
# hash so a mirror change cannot silently alter the shipped rootfs.
