SKIP_PREFIX = (".PKGINFO", ".SIGN", ".pre-", ".post-", ".trigger")
CA_DIR = "/usr/share/ca-certificates"


def digest(path):
    sha = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            sha.update(chunk)
    return sha.hexdigest()


def fetch(cache, repo, name, expected):
    path = os.path.join(cache, name)
    if os.path.exists(path) and digest(path) == expected:
        return path
    os.makedirs(cache, exist_ok=True)
    url = repo + "/" + name
    print("downloading", url)
    tmp = path + ".part"
    subprocess.run(["curl", "-fsSL", "-o", tmp, url], check=True)
    actual = digest(tmp)
    if actual != expected:
        os.remove(tmp)
        raise SystemExit("checksum mismatch for %s: %s" % (name, actual))
    os.replace(tmp, path)
    return path


def member_filter(member):
    name = member.name.lstrip("./")
    if not name or name.startswith(SKIP_PREFIX):
        return None
    member.name = name
    member.mode &= 0o777
    member.uid = 0
    member.gid = 0
    return member


def write_ca_bundle(data):
    """Assemble the bundle update-ca-certificates would have produced."""
    sources = sorted(glob.glob(os.path.join(data, CA_DIR.lstrip("/"), "**", "*.crt"),
                               recursive=True))
    if not sources:
        raise SystemExit("ca-certificates package shipped no .crt files")
    target = os.path.join(data, "etc", "ssl", "certs", "ca-certificates.crt")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    count = 0
    with open(target, "wb") as out:
        for path in sources:
            with open(path, "rb") as handle:
                body = handle.read()
            if b"BEGIN CERTIFICATE" not in body:
                continue
            out.write(body)
            if not body.endswith(b"\n"):
                out.write(b"\n")
            count += 1
    if count == 0:
        raise SystemExit("no PEM certificates found in ca-certificates package")
    # openssl and requests use cert.pem on some Alpine builds; node uses the
    # hashed bundle path above.
    link = os.path.join(data, "etc", "ssl", "cert.pem")
    if not os.path.lexists(link):
        os.symlink("certs/ca-certificates.crt", link)
    print("wrote %d certificates to %s" % (count, target))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True,
                        help="rootfs data directory (the fakefs tree)")
    parser.add_argument("--cache", required=True,
                        help="directory holding the pinned .apk files")
    args = parser.parse_args()

    os.makedirs(args.data, exist_ok=True)
    for repo, name, expected in PACKAGES:
        path = fetch(args.cache, repo, name, expected)
        with tarfile.open(path, "r:gz") as archive:
            members = [m for m in (member_filter(m)
                                   for m in archive.getmembers()) if m]
            archive.extractall(args.data, members=members, filter="tar")

    node = os.path.join(args.data, "usr", "bin", "node")
    npm = os.path.join(args.data, "usr", "bin", "npm")
    if not os.path.exists(node):
        raise SystemExit("node missing after extraction")
    if not os.path.lexists(npm):
        raise SystemExit("npm missing after extraction")
    write_ca_bundle(args.data)
    print("node installed into", args.data)


if __name__ == "__main__":
    main()
